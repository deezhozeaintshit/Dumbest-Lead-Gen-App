// Helper functions
export function getAllCategories(): BusinessCategory[] {
  return BUSINESS_TAXONOMY;
}

export function getCategoryById(id: string): BusinessCategory | undefined {
  return BUSINESS_TAXONOMY.find((c) => c.id === id);
}

export function getAllSubNiches(): string[] {
  return BUSINESS_TAXONOMY.flatMap((c) => c.subNiches);
}

export function searchTaxonomy(term: string): { category: BusinessCategory; subNiche: string }[] {
  const q = term.toLowerCase().trim();
  if (!q) return [];

  const results: { category: BusinessCategory; subNiche: string }[] = [];

  for (const cat of BUSINESS_TAXONOMY) {
    for (const sub of cat.subNiches) {
      if (
        sub.toLowerCase().includes(q) ||
        cat.name.toLowerCase().includes(q) ||
        cat.description.toLowerCase().includes(q)
      ) {
        results.push({ category: cat, subNiche: sub });
      }
    }
  }

  return results;
}
